function setLang(lang){
  localStorage.setItem("lang", lang);
  location.reload();
}
const $ = (sel)=> document.querySelector(sel);

/* Banner: rotate phrases with soft fade */
function rotatePhrases(t){
  const el = $("#hero-title");
  let i = 0;
  const swap = ()=>{
    el.classList.remove("show");
    setTimeout(()=>{
      el.textContent = t.phrases[i % t.phrases.length];
      i++;
      el.classList.add("show");
    }, 80);
  };
  el.classList.add("show");
  setInterval(swap, 4000);
}

/* Smooth anchors */
function smoothScroll(){
  document.querySelectorAll('a[href^="#"]').forEach(a=>{
    a.addEventListener("click", e=>{
      const id = a.getAttribute("href");
      if(id.length>1 && $(id)){
        e.preventDefault();
        $(id).scrollIntoView({behavior:"smooth", block:"start"});
      }
    });
  });
}

/* Reveal on scroll */
function revealOnScroll(){
  const obs = new IntersectionObserver((entries)=>{
    entries.forEach(en=>{ if(en.isIntersecting) en.target.classList.add("in"); });
  }, {threshold:.15});
  document.querySelectorAll("[data-animate]").forEach(el=> obs.observe(el));
}

function fill(){
  const lang = localStorage.getItem("lang") || "pt";
  const t = TEXT[lang];

  // header
  $("#brand").textContent = t.brand;
  $("#nav-home").textContent = t.nav.home;
  $("#nav-about").textContent = t.nav.about;
  $("#nav-projects").textContent = t.nav.projects;
  $("#nav-contact").textContent = t.nav.contact;

  // hero
  $("#hero-sub").textContent = t.hero_sub;
  $("#hero-cta").textContent = t.hero_cta;
  rotatePhrases(t);

  // about
  $("#about-title").textContent = t.about_title;
  $("#about-body").innerText = t.about_body;

  // circles
  const row = $("#circles");
  row.innerHTML = "";
  t.circles.forEach(([label, url, href])=>{
    const wrap = document.createElement(href ? "a" : "div");
    if(href){ wrap.href = href; wrap.className=""; }
    wrap.style.textAlign="center";
    const c = document.createElement("div");
    c.className="circle";
    c.style.backgroundImage = `url('${url}')`;
    const cap = document.createElement("div");
    cap.className = "circle-label";
    cap.textContent = label;
    wrap.appendChild(c); wrap.appendChild(cap);
    row.appendChild(wrap);
  });

  // projects
  $("#projects-title").textContent = t.projects_title;
  const grid = $("#projects-grid");
  grid.innerHTML = "";
  t.projects.forEach(([name, desc, link])=>{
    const card = document.createElement("div");
    card.className = "project";
    const pill = document.createElement("a"); pill.className="pill"; pill.href = link; pill.textContent = name;
    const h3 = document.createElement("h3");
    const h3a = document.createElement("a"); h3a.href = link; h3a.textContent = name; h3.appendChild(h3a);
    const p = document.createElement("p"); p.textContent = desc;
    const a = document.createElement("a"); a.className="button"; a.href = link; a.target="_blank"; a.rel="noopener"; a.textContent = t.hero_cta;
    card.append(pill,h3,p,a);
    grid.appendChild(card);
  });

  // contacts
  $("#contact-title").textContent = t.contact_title;
  const list = $("#contact-list");
  list.innerHTML = "";
  t.contact_items.forEach(([label, text, href])=>{
    const a = document.createElement("a");
    a.href = href; a.target="_blank"; a.rel="noopener";
    a.innerHTML = `<strong>${label}</strong><div class="small">${text}</div>`;
    a.className = "list-item";
    a.style.display="flex"; a.style.gap="12px"; a.style.alignItems="center";
    a.classList.add("card");
    list.appendChild(a);
  });

  // footer
  $("#footer").textContent = t.footer.replace("{year}", new Date().getFullYear());

  // active language
  document.querySelectorAll(".lang button").forEach(b=> b.classList.toggle("active", b.dataset.lang===lang));

  smoothScroll();
  revealOnScroll();
}

document.addEventListener("DOMContentLoaded", fill);
